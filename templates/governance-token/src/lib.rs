//! A SEP-41 governance token (`soroban_sdk::token::TokenInterface`) with vote
//! delegation and historical ledger checkpoints queried via binary search.
//!
//! Holders delegate their voting power to a representative (or to themselves)
//! with `delegate`. Every mint, transfer, burn, or delegation change updates
//! the affected delegates' voting power and appends (or overwrites in the same
//! ledger) a [`Checkpoint`] recording `(ledger, votes)`. Governance contracts
//! query `get_past_votes(account, proposal_snapshot_ledger)` and
//! `get_past_total_supply(proposal_snapshot_ledger)` using binary search so
//! tokens acquired or moved after a proposal opens cannot influence that vote.
//!
//! Generated by [soroban-forge](https://github.com/soroban-forge-labs/soroban-forge).

#![no_std]

use soroban_sdk::{
    contract, contracterror, contractevent, contractimpl, contracttype, panic_with_error,
    token::TokenInterface, Address, Env, MuxedAddress, String, Vec,
};

/// Ledgers per day, assuming ~5s per ledger.
pub const DAY_IN_LEDGERS: u32 = 17_280;
/// Persistent storage TTL (30 days).
pub const PERSISTENT_TTL: u32 = 30 * DAY_IN_LEDGERS;
/// Extend persistent storage TTL when remaining lifetime drops below this threshold.
pub const PERSISTENT_TTL_THRESHOLD: u32 = PERSISTENT_TTL - DAY_IN_LEDGERS;

#[contracterror]
#[derive(Copy, Clone, Debug, Eq, PartialEq, PartialOrd, Ord)]
#[repr(u32)]
pub enum Error {
    /// Token amount must not be negative.
    NegativeAmount = 1,
    /// Account balance is insufficient for transfer or burn.
    InsufficientBalance = 2,
    /// Spender allowance is insufficient or expired for `transfer_from` / `burn_from`.
    InsufficientAllowance = 3,
    /// Approval `expiration_ledger` is in the past for a positive allowance.
    InvalidExpiration = 4,
    /// Requested `ledger` in `get_past_votes` or `get_past_total_supply` has not closed yet.
    FutureLookup = 5,
    /// Arithmetic overflow when updating balances, supply, or voting power.
    Overflow = 6,
    /// Requested checkpoint index is out of bounds (`>= num_checkpoints(account)`).
    CheckpointNotFound = 7,
}

/// A historical voting-power (or total-supply) snapshot starting at `ledger`.
#[contracttype]
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct Checkpoint {
    pub ledger: u32,
    pub votes: i128,
}

#[contracttype]
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct AllowanceDataKey {
    pub from: Address,
    pub spender: Address,
}

#[contracttype]
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct AllowanceValue {
    pub amount: i128,
    pub expiration_ledger: u32,
}

#[contracttype]
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct TokenMetadata {
    pub decimals: u32,
    pub name: String,
    pub symbol: String,
}

#[contracttype]
#[derive(Clone)]
pub enum DataKey {
    /// Instance storage: admin address allowed to mint.
    Admin,
    /// Instance storage: token decimals, name, and symbol.
    Metadata,
    /// Instance storage: current total token supply (`i128`).
    TotalSupply,
    /// Persistent storage: token balance of an account (`i128`).
    Balance(Address),
    /// Temporary storage: spender allowance (`AllowanceValue`).
    Allowance(AllowanceDataKey),
    /// Persistent storage: current delegatee chosen by an account (`Address`).
    Delegate(Address),
    /// Persistent storage: current total delegated voting power of a delegatee (`i128`).
    Votes(Address),
    /// Persistent storage: chronological `Vec<Checkpoint>` of voting power for a delegatee.
    Checkpoints(Address),
    /// Persistent storage: chronological `Vec<Checkpoint>` of total token supply.
    SupplyCheckpoints,
}

