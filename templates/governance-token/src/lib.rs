// --- internal helpers -------------------------------------------------------

fn check_nonnegative(env: &Env, amount: i128) {
    if amount < 0 {
        panic_with_error!(env, Error::NegativeAmount);
    }
}

fn read_balance(env: &Env, id: &Address) -> i128 {
    let key = DataKey::Balance(id.clone());
    if let Some(balance) = env.storage().persistent().get::<_, i128>(&key) {
        env.storage()
            .persistent()
            .extend_ttl(&key, PERSISTENT_TTL_THRESHOLD, PERSISTENT_TTL);
        balance
    } else {
        0
    }
}

fn write_balance(env: &Env, id: &Address, amount: i128) {
    let key = DataKey::Balance(id.clone());
    env.storage().persistent().set(&key, &amount);
    env.storage()
        .persistent()
        .extend_ttl(&key, PERSISTENT_TTL_THRESHOLD, PERSISTENT_TTL);
}

fn spend_balance(env: &Env, id: &Address, amount: i128) {
    let balance = read_balance(env, id);
    if balance < amount {
        panic_with_error!(env, Error::InsufficientBalance);
    }
    write_balance(env, id, balance - amount);
}

fn receive_balance(env: &Env, id: &Address, amount: i128) {
    let balance = read_balance(env, id);
    let updated = balance
        .checked_add(amount)
        .unwrap_or_else(|| panic_with_error!(env, Error::Overflow));
    write_balance(env, id, updated);
}

fn read_total_supply(env: &Env) -> i128 {
    env.storage()
        .instance()
        .get(&DataKey::TotalSupply)
        .unwrap_or(0)
}

fn write_total_supply(env: &Env, supply: i128) {
    env.storage().instance().set(&DataKey::TotalSupply, &supply);
}

fn read_allowance(env: &Env, from: &Address, spender: &Address) -> AllowanceValue {
    let key = DataKey::Allowance(AllowanceDataKey {
        from: from.clone(),
        spender: spender.clone(),
    });
    match env.storage().temporary().get::<_, AllowanceValue>(&key) {
        Some(allowance) if allowance.expiration_ledger < env.ledger().sequence() => {
            AllowanceValue {
                amount: 0,
                expiration_ledger: allowance.expiration_ledger,
            }
        }
        Some(allowance) => allowance,
        None => AllowanceValue {
            amount: 0,
            expiration_ledger: 0,
        },
    }
}

fn write_allowance(
    env: &Env,
    from: &Address,
    spender: &Address,
    amount: i128,
    expiration_ledger: u32,
) {
    if amount > 0 && expiration_ledger < env.ledger().sequence() {
        panic_with_error!(env, Error::InvalidExpiration);
    }
    let key = DataKey::Allowance(AllowanceDataKey {
        from: from.clone(),
        spender: spender.clone(),
    });
    env.storage().temporary().set(
        &key,
        &AllowanceValue {
            amount,
            expiration_ledger,
        },
    );
    if amount > 0 {
        let live_for = expiration_ledger - env.ledger().sequence();
        if live_for > 0 {
            env.storage().temporary().extend_ttl(&key, live_for, live_for);
        }
    }
}

fn spend_allowance(env: &Env, from: &Address, spender: &Address, amount: i128) {
    let allowance = read_allowance(env, from, spender);
    if allowance.amount < amount {
        panic_with_error!(env, Error::InsufficientAllowance);
    }
    if amount > 0 {
        write_allowance(
            env,
            from,
            spender,
            allowance.amount - amount,
            allowance.expiration_ledger,
        );
    }
}

fn read_delegate(env: &Env, account: &Address) -> Option<Address> {
    let key = DataKey::Delegate(account.clone());
    if let Some(delegatee) = env.storage().persistent().get::<_, Address>(&key) {
        env.storage()
            .persistent()
            .extend_ttl(&key, PERSISTENT_TTL_THRESHOLD, PERSISTENT_TTL);
        Some(delegatee)
    } else {
        None
    }
}

fn write_delegate(env: &Env, account: &Address, delegatee: &Address) {
    let key = DataKey::Delegate(account.clone());
    env.storage().persistent().set(&key, delegatee);
    env.storage()
        .persistent()
        .extend_ttl(&key, PERSISTENT_TTL_THRESHOLD, PERSISTENT_TTL);
}

fn read_votes(env: &Env, delegate: &Address) -> i128 {
    let key = DataKey::Votes(delegate.clone());
    if let Some(votes) = env.storage().persistent().get::<_, i128>(&key) {
        env.storage()
            .persistent()
            .extend_ttl(&key, PERSISTENT_TTL_THRESHOLD, PERSISTENT_TTL);
        votes
    } else {
        0
    }
}

fn write_votes(env: &Env, delegate: &Address, votes: i128) {
    let key = DataKey::Votes(delegate.clone());
    env.storage().persistent().set(&key, &votes);
    env.storage()
        .persistent()
        .extend_ttl(&key, PERSISTENT_TTL_THRESHOLD, PERSISTENT_TTL);
}

fn read_checkpoints(env: &Env, key: &DataKey) -> Vec<Checkpoint> {
    if let Some(checkpoints) = env.storage().persistent().get::<_, Vec<Checkpoint>>(key) {
        env.storage()
            .persistent()
            .extend_ttl(key, PERSISTENT_TTL_THRESHOLD, PERSISTENT_TTL);
        checkpoints
    } else {
        Vec::new(env)
    }
}

/// Record a new checkpoint at the current ledger sequence, overwriting the last
/// checkpoint in-place if it was already written in the same ledger.
fn write_checkpoint(env: &Env, key: &DataKey, new_votes: i128) {
    let mut checkpoints = read_checkpoints(env, key);
    let current_ledger = env.ledger().sequence();
    let len = checkpoints.len();

    if len > 0 && checkpoints.get(len - 1).unwrap().ledger == current_ledger {
        checkpoints.set(
            len - 1,
            Checkpoint {
                ledger: current_ledger,
                votes: new_votes,
            },
        );
    } else {
        checkpoints.push_back(Checkpoint {
            ledger: current_ledger,
            votes: new_votes,
        });
    }

    env.storage().persistent().set(key, &checkpoints);
    env.storage()
        .persistent()
        .extend_ttl(key, PERSISTENT_TTL_THRESHOLD, PERSISTENT_TTL);
}

/// Upper-bound binary search over a chronological `Vec<Checkpoint>` to find the
/// voting power (or total supply) active at `ledger`.
fn binary_search_checkpoints(env: &Env, key: &DataKey, ledger: u32) -> i128 {
    if ledger > env.ledger().sequence() {
        panic_with_error!(env, Error::FutureLookup);
    }

    let checkpoints = read_checkpoints(env, key);
    let len = checkpoints.len();
    if len == 0 {
        return 0;
    }

    // If the queried ledger precedes the earliest checkpoint, voting power was 0.
    if ledger < checkpoints.get(0).unwrap().ledger {
        return 0;
    }

    // Fast path: queried ledger is at or after the most recent checkpoint.
    let last = checkpoints.get(len - 1).unwrap();
    if ledger >= last.ledger {
        return last.votes;
    }

    // Binary search for the largest index `low` with `checkpoints[low].ledger <= ledger`.
    let mut low: u32 = 0;
    let mut high: u32 = len - 1;
    while low < high {
        let mid = low + (high - low).div_ceil(2);
        if checkpoints.get(mid).unwrap().ledger <= ledger {
            low = mid;
        } else {
            high = mid - 1;
        }
    }

    checkpoints.get(low).unwrap().votes
}

/// Move `amount` of delegated voting power from `src_opt` to `dst_opt`, updating
/// their vote totals, checkpoints, and emitting [`DelegateVotesChanged`] events.
fn move_delegates(
    env: &Env,
    src_opt: Option<&Address>,
    dst_opt: Option<&Address>,
    amount: i128,
) {
    if amount <= 0 || src_opt == dst_opt {
        return;
    }

    if let Some(src) = src_opt {
        let prev = read_votes(env, src);
        let new_votes = prev
            .checked_sub(amount)
            .unwrap_or_else(|| panic_with_error!(env, Error::InsufficientBalance));
        write_votes(env, src, new_votes);
        write_checkpoint(env, &DataKey::Checkpoints(src.clone()), new_votes);
        DelegateVotesChanged {
            delegate: src.clone(),
            previous_votes: prev,
            new_votes,
        }
        .publish(env);
    }

    if let Some(dst) = dst_opt {
        let prev = read_votes(env, dst);
        let new_votes = prev
            .checked_add(amount)
            .unwrap_or_else(|| panic_with_error!(env, Error::Overflow));
        write_votes(env, dst, new_votes);
        write_checkpoint(env, &DataKey::Checkpoints(dst.clone()), new_votes);
        DelegateVotesChanged {
            delegate: dst.clone(),
            previous_votes: prev,
            new_votes,
        }
        .publish(env);
    }
}

#[contract]
pub struct GovernanceTokenContract;

#[contractimpl]
impl GovernanceTokenContract {
    /// Deploy-time setup: sets the mint admin and token metadata (`decimals`, `name`, `symbol`).
    pub fn __constructor(env: Env, admin: Address, decimals: u32, name: String, symbol: String) {
        env.storage().instance().set(&DataKey::Admin, &admin);
        env.storage().instance().set(
            &DataKey::Metadata,
            &TokenMetadata {
                decimals,
                name,
                symbol,
            },
        );
        env.storage().instance().set(&DataKey::TotalSupply, &0i128);
    }

    /// Mint `amount` new tokens to `to` (admin only).
    ///
    /// If `to` has already delegated its voting power, `to`'s delegate receives
    /// `amount` additional votes and a new checkpoint.
    pub fn mint(env: Env, to: Address, amount: i128) {
        check_nonnegative(&env, amount);
        let admin: Address = env.storage().instance().get(&DataKey::Admin).unwrap();
        admin.require_auth();

        let new_supply = read_total_supply(&env)
            .checked_add(amount)
            .unwrap_or_else(|| panic_with_error!(&env, Error::Overflow));
        receive_balance(&env, &to, amount);
        write_total_supply(&env, new_supply);
        if amount > 0 {
            write_checkpoint(&env, &DataKey::SupplyCheckpoints, new_supply);
        }

        let to_delegate = read_delegate(&env, &to);
        move_delegates(&env, None, to_delegate.as_ref(), amount);

        Mint { to, amount }.publish(&env);
    }

    /// Return the current admin address.
    pub fn admin(env: Env) -> Address {
        env.storage().instance().get(&DataKey::Admin).unwrap()
    }

    /// Return the current total token supply.
    pub fn total_supply(env: Env) -> i128 {
        read_total_supply(&env)
    }

    /// Delegate all voting power of `account`'s current and future token balance
    /// to `delegatee`.
    ///
    /// Holders must call `delegate` (including self-delegation where
    /// `account == delegatee`) to activate voting power checkpoints.
    pub fn delegate(env: Env, account: Address, delegatee: Address) {
        account.require_auth();
        let old_delegate = read_delegate(&env, &account);
        write_delegate(&env, &account, &delegatee);

        let balance = read_balance(&env, &account);
        move_delegates(&env, old_delegate.as_ref(), Some(&delegatee), balance);

        DelegateChanged {
            delegator: account,
            from_delegate: old_delegate,
            to_delegate: delegatee,
        }
        .publish(&env);
    }

    /// Return the address that `account` is currently delegating its votes to,
    /// or `None` if `account` has never delegated.
    pub fn delegates(env: Env, account: Address) -> Option<Address> {
        read_delegate(&env, &account)
    }

    /// Return the current delegated voting power of `account`.
    pub fn get_votes(env: Env, account: Address) -> i128 {
        read_votes(&env, &account)
    }

    /// Return the delegated voting power of `account` at a past `ledger` sequence,
    /// looked up via binary search over `account`'s checkpoints.
    ///
    /// Fails with [`Error::FutureLookup`] if `ledger > env.ledger().sequence()`.
    pub fn get_past_votes(env: Env, account: Address, ledger: u32) -> i128 {
        binary_search_checkpoints(&env, &DataKey::Checkpoints(account), ledger)
    }

    /// Return the total token supply at a past `ledger` sequence, looked up via
    /// binary search over the supply checkpoints.
    ///
    /// Fails with [`Error::FutureLookup`] if `ledger > env.ledger().sequence()`.
    pub fn get_past_total_supply(env: Env, ledger: u32) -> i128 {
        binary_search_checkpoints(&env, &DataKey::SupplyCheckpoints, ledger)
    }

    /// Return the number of voting-power checkpoints recorded for `account`.
    pub fn num_checkpoints(env: Env, account: Address) -> u32 {
        read_checkpoints(&env, &DataKey::Checkpoints(account)).len()
    }

    /// Return the `index`-th voting-power [`Checkpoint`] for `account`.
    ///
    /// Fails with [`Error::CheckpointNotFound`] if `index >= num_checkpoints(account)`.
    pub fn checkpoints(env: Env, account: Address, index: u32) -> Checkpoint {
        let list = read_checkpoints(&env, &DataKey::Checkpoints(account));
        if index >= list.len() {
            panic_with_error!(&env, Error::CheckpointNotFound);
        }
        list.get(index).unwrap()
    }
}

#[contractimpl]
impl TokenInterface for GovernanceTokenContract {
    fn allowance(env: Env, from: Address, spender: Address) -> i128 {
        read_allowance(&env, &from, &spender).amount
    }

    fn approve(env: Env, from: Address, spender: Address, amount: i128, expiration_ledger: u32) {
        from.require_auth();
        check_nonnegative(&env, amount);
        write_allowance(&env, &from, &spender, amount, expiration_ledger);
        Approve {
            from,
            spender,
            amount,
            expiration_ledger,
        }
        .publish(&env);
    }

    fn balance(env: Env, id: Address) -> i128 {
        read_balance(&env, &id)
    }

    fn transfer(env: Env, from: Address, to: MuxedAddress, amount: i128) {
        from.require_auth();
        check_nonnegative(&env, amount);
        let to_addr = to.address();
        spend_balance(&env, &from, amount);
        receive_balance(&env, &to_addr, amount);

        let from_delegate = read_delegate(&env, &from);
        let to_delegate = read_delegate(&env, &to_addr);
        move_delegates(&env, from_delegate.as_ref(), to_delegate.as_ref(), amount);

        Transfer {
            from,
            to: to_addr,
            amount,
        }
        .publish(&env);
    }

    fn transfer_from(env: Env, spender: Address, from: Address, to: Address, amount: i128) {
        spender.require_auth();
        check_nonnegative(&env, amount);
        spend_allowance(&env, &from, &spender, amount);
        spend_balance(&env, &from, amount);
        receive_balance(&env, &to, amount);

        let from_delegate = read_delegate(&env, &from);
        let to_delegate = read_delegate(&env, &to);
        move_delegates(&env, from_delegate.as_ref(), to_delegate.as_ref(), amount);

        Transfer { from, to, amount }.publish(&env);
    }

    fn burn(env: Env, from: Address, amount: i128) {
        from.require_auth();
        check_nonnegative(&env, amount);
        spend_balance(&env, &from, amount);

        let new_supply = read_total_supply(&env)
            .checked_sub(amount)
            .unwrap_or_else(|| panic_with_error!(&env, Error::InsufficientBalance));
        write_total_supply(&env, new_supply);
        if amount > 0 {
            write_checkpoint(&env, &DataKey::SupplyCheckpoints, new_supply);
        }

        let from_delegate = read_delegate(&env, &from);
        move_delegates(&env, from_delegate.as_ref(), None, amount);

        Burn { from, amount }.publish(&env);
    }

    fn burn_from(env: Env, spender: Address, from: Address, amount: i128) {
        spender.require_auth();
        check_nonnegative(&env, amount);
        spend_allowance(&env, &from, &spender, amount);
        spend_balance(&env, &from, amount);

        let new_supply = read_total_supply(&env)
            .checked_sub(amount)
            .unwrap_or_else(|| panic_with_error!(&env, Error::InsufficientBalance));
        write_total_supply(&env, new_supply);
        if amount > 0 {
            write_checkpoint(&env, &DataKey::SupplyCheckpoints, new_supply);
        }

        let from_delegate = read_delegate(&env, &from);
        move_delegates(&env, from_delegate.as_ref(), None, amount);

        Burn { from, amount }.publish(&env);
    }

    fn decimals(env: Env) -> u32 {
        let meta: TokenMetadata = env.storage().instance().get(&DataKey::Metadata).unwrap();
        meta.decimals
    }

    fn name(env: Env) -> String {
        let meta: TokenMetadata = env.storage().instance().get(&DataKey::Metadata).unwrap();
        meta.name
    }

    fn symbol(env: Env) -> String {
        let meta: TokenMetadata = env.storage().instance().get(&DataKey::Metadata).unwrap();
        meta.symbol
    }
}

