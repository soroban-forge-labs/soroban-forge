//! Lottery / raffle using a commit-reveal scheme for randomness.
//!
//! * **Enter** — during the commit phase, entrants submit a commitment
//!   (`sha256(entrant_xdr || nonce)`) that hides a secret nonce they will reveal later.
//! * **Reveal** — during the reveal phase, entrants reveal their nonce; the
//!   contract checks it hashes to their commitment.
//! * **Draw** — after the reveal phase ends, anyone can call `draw`, which
//!   XORs every revealed nonce into a single seed and picks the winner from
//!   the entrants who successfully revealed. Entrants who never reveal
//!   forfeit the draw — this is what makes the scheme resistant to a single
//!   party biasing the outcome, since no one controls the final seed alone.
//!
//! ### Security & Limitations: Last-Revealer Advantage
//! Plain commit-reveal schemes suffer from a known structural limitation:
//! the **last participant to reveal can calculate the final seed both with
//! and without their nonce before deciding whether to reveal**.
//!
//! If withholding their reveal produces a winning outcome for themselves or
//! a colluding party, they can simply choose not to reveal. Because entrants
//! who do not reveal are simply excluded from the draw without penalty, the
//! last revealer can steer or bias the outcome.
//!
//! **When not to use this template:**
//! Do not use this plain commit-reveal template for high-value raffles,
//! production lotteries, or gaming scenarios where participants have a financial
//! incentive to withhold their secret nonce. For high-stakes applications on
//! Stellar/Soroban, use a Verifiable Random Function (VRF) oracle instead of
//! plain commit-reveal.
//!
//! Generated by [soroban-forge](https://github.com/soroban-forge-labs/soroban-forge).

#![no_std]

use soroban_sdk::{
    contract, contracterror, contractevent, contractimpl, contracttype, symbol_short, Address, Bytes,
    BytesN, Env, Vec,
};

pub const DAY_IN_LEDGERS: u32 = 17_280;
pub const INSTANCE_TTL: u32 = 30 * DAY_IN_LEDGERS;
pub const INSTANCE_TTL_THRESHOLD: u32 = INSTANCE_TTL - DAY_IN_LEDGERS;
pub const PERSISTENT_TTL: u32 = 30 * DAY_IN_LEDGERS;
pub const PERSISTENT_TTL_THRESHOLD: u32 = PERSISTENT_TTL - DAY_IN_LEDGERS;

#[contracterror]
#[derive(Copy, Clone, Debug, Eq, PartialEq)]
#[repr(u32)]
pub enum Error {
    /// `accept_admin` or `cancel_admin_proposal` was called with no handover pending.
    NoPendingAdmin = 1,
}

/// Emitted when the current admin proposes a new admin.
#[contractevent]
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct AdminProposed {
    #[topic]
    pub admin: Address,
    pub pending: Address,
}

/// Emitted when the pending admin accepts and becomes the admin.
#[contractevent]
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct AdminAccepted {
    #[topic]
    pub old_admin: Address,
    pub new_admin: Address,
}

/// Emitted when the current admin cancels a pending handover.
#[contractevent]
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct AdminProposalCancelled {
    #[topic]
    pub admin: Address,
    pub pending: Address,
}

#[contracttype]
pub enum DataKey {
    Admin,
    PendingAdmin,
    CommitDeadline,
    RevealDeadline,
    Entrants,
    Commitment(Address),
    CommitmentUsed(BytesN<32>),
    Revealed(Address),
    Winner,
    Drawn,
}

#[contract]
pub struct LotteryContract;

#[contractimpl]
impl LotteryContract {
    /// Initialize the lottery.
    ///
    /// * `admin` — address that configures the lottery
    /// * `commit_deadline` — ledger timestamp after which entries close
    /// * `reveal_deadline` — ledger timestamp after which reveals close and
    ///   the winner can be drawn
    ///
    /// Can only be called once: a second call would let anyone replace the
    /// admin, move the deadlines and wipe the entrants or a drawn winner.
    pub fn initialize(env: Env, admin: Address, commit_deadline: u64, reveal_deadline: u64) {
        if env.storage().instance().has(&DataKey::Admin) {
            panic!("already initialized");
        }
        admin.require_auth();

        if reveal_deadline <= commit_deadline {
            panic!("reveal deadline must be after commit deadline");
        }

        env.storage().instance().set(&DataKey::Admin, &admin);
        env.storage()
            .instance()
            .set(&DataKey::CommitDeadline, &commit_deadline);
        env.storage()
            .instance()
            .set(&DataKey::RevealDeadline, &reveal_deadline);
        env.storage()
            .instance()
            .set(&DataKey::Entrants, &Vec::<Address>::new(&env));
        env.storage().instance().set(&DataKey::Drawn, &false);
    }

    /// Propose `new_admin` as the next admin. Current admin only.
    ///
    /// Nothing changes until `new_admin` calls `accept_admin`. Calling this
    /// again replaces any earlier pending proposal.
    pub fn propose_admin(env: Env, new_admin: Address) {
        let admin: Address = env.storage().instance().get(&DataKey::Admin).unwrap();
        admin.require_auth();
        env.storage()
            .instance()
            .set(&DataKey::PendingAdmin, &new_admin);
        AdminProposed {
            admin,
            pending: new_admin,
        }
        .publish(&env);
    }

    /// Accept a pending admin handover. Pending admin only.
    ///
    /// Fails with `NoPendingAdmin` if no handover is pending. Only the
    /// proposed address can satisfy the auth check, so any other caller is
    /// rejected.
    pub fn accept_admin(env: Env) -> Result<(), Error> {
        let pending: Address = env
            .storage()
            .instance()
            .get(&DataKey::PendingAdmin)
            .ok_or(Error::NoPendingAdmin)?;
        pending.require_auth();
        let old_admin: Address = env.storage().instance().get(&DataKey::Admin).unwrap();
        env.storage().instance().set(&DataKey::Admin, &pending);
        env.storage().instance().remove(&DataKey::PendingAdmin);
        AdminAccepted {
            old_admin,
            new_admin: pending,
        }
        .publish(&env);
        Ok(())
    }

    /// Cancel a pending admin handover. Current admin only.
    pub fn cancel_admin_proposal(env: Env) -> Result<(), Error> {
        let admin: Address = env.storage().instance().get(&DataKey::Admin).unwrap();
        admin.require_auth();
        let pending: Address = env
            .storage()
            .instance()
            .get(&DataKey::PendingAdmin)
            .ok_or(Error::NoPendingAdmin)?;
        env.storage().instance().remove(&DataKey::PendingAdmin);
        AdminProposalCancelled { admin, pending }.publish(&env);
        Ok(())
    }

    /// Return the current admin.
    pub fn admin(env: Env) -> Address {
        env.storage().instance().get(&DataKey::Admin).unwrap()
    }

    /// Return the pending admin, if a handover is in progress.
    pub fn pending_admin(env: Env) -> Option<Address> {
        env.storage().instance().get(&DataKey::PendingAdmin)
    }

    /// Compute the commitment for an entrant and nonce: `sha256(entrant_xdr || nonce)`.
    pub fn commitment(env: Env, entrant: Address, nonce: BytesN<32>) -> BytesN<32> {
        let mut buf = Bytes::new(&env);
        buf.append(&entrant.to_xdr(&env));
        let nonce_bytes: Bytes = nonce.into();
        buf.append(&nonce_bytes);
        env.crypto().sha256(&buf).into()
    }

    /// Enter the lottery with a commitment to a secret nonce.
    ///
    /// `commitment` must equal `sha256(entrant_xdr || nonce)` for the nonce that will be
    /// passed to `reveal` later. Must be called before the commit deadline.
    pub fn enter(env: Env, entrant: Address, commitment: BytesN<32>) {
        entrant.require_auth();
        env.storage()
            .instance()
            .extend_ttl(INSTANCE_TTL_THRESHOLD, INSTANCE_TTL);

        let now = env.ledger().timestamp();
        let commit_deadline: u64 = env
            .storage()
            .instance()
            .get(&DataKey::CommitDeadline)
            .unwrap();
        if now >= commit_deadline {
            panic!("commit phase has ended");
        }

        let key = DataKey::Commitment(entrant.clone());
        if env.storage().instance().has(&key) {
            panic!("already entered");
        }

        let comm_used_key = DataKey::CommitmentUsed(commitment.clone());
        if env.storage().instance().has(&comm_used_key) {
            panic!("duplicate commitment");
        }
        env.storage().instance().set(&comm_used_key, &true);
        env.storage().instance().set(&key, &commitment);

        let mut entrants: Vec<Address> = env.storage().instance().get(&DataKey::Entrants).unwrap();
        entrants.push_back(entrant.clone());
        env.storage().instance().set(&DataKey::Entrants, &entrants);

        env.events().publish((symbol_short!("enter"), entrant), ());
    }

    /// Reveal the nonce behind a prior commitment.
    ///
    /// Must be called during the reveal window (after the commit deadline,
    /// before the reveal deadline) with the nonce whose sha256 matches the
    /// commitment submitted in `enter`.
    pub fn reveal(env: Env, entrant: Address, nonce: BytesN<32>) {
        entrant.require_auth();
        env.storage()
            .instance()
            .extend_ttl(INSTANCE_TTL_THRESHOLD, INSTANCE_TTL);

        let now = env.ledger().timestamp();
        let commit_deadline: u64 = env
            .storage()
            .instance()
            .get(&DataKey::CommitDeadline)
            .unwrap();
        let reveal_deadline: u64 = env
            .storage()
            .instance()
            .get(&DataKey::RevealDeadline)
            .unwrap();
        if now < commit_deadline || now >= reveal_deadline {
            panic!("not in reveal phase");
        }

        let commitment: BytesN<32> = env
            .storage()
            .instance()
            .get(&DataKey::Commitment(entrant.clone()))
            .unwrap_or_else(|| panic!("no entry to reveal"));

        let revealed_key = DataKey::Revealed(entrant.clone());
        if env.storage().instance().has(&revealed_key) {
            panic!("already revealed");
        }

        let mut buf = Bytes::new(&env);
        buf.append(&entrant.to_xdr(&env));
        let nonce_bytes: Bytes = nonce.clone().into();
        buf.append(&nonce_bytes);
        let computed: BytesN<32> = env.crypto().sha256(&buf).into();
        if computed != commitment {
            panic!("nonce does not match commitment");
        }

        env.storage().instance().set(&revealed_key, &nonce);

        env.events()
            .publish((symbol_short!("reveal"), entrant), ());
    }

    /// Draw the winner from the entrants who successfully revealed.
    ///
    /// Callable by anyone once the reveal deadline has passed. The random
    /// seed is derived by XOR-ing every revealed nonce together, so no
    /// single entrant controls the outcome.
    pub fn draw(env: Env) -> Address {
        env.storage()
            .instance()
            .extend_ttl(INSTANCE_TTL_THRESHOLD, INSTANCE_TTL);
        
        let now = env.ledger().timestamp();
        let reveal_deadline: u64 = env
            .storage()
            .instance()
            .get(&DataKey::RevealDeadline)
            .unwrap();
        if now < reveal_deadline {
            panic!("reveal phase has not ended");
        }

        let drawn: bool = env.storage().instance().get(&DataKey::Drawn).unwrap();
        if drawn {
            panic!("winner already drawn");
        }

        let entrants: Vec<Address> = env.storage().instance().get(&DataKey::Entrants).unwrap();

        let mut revealed_entrants: Vec<Address> = Vec::new(&env);
        let mut seed = [0_u8; 32];
        for entrant in entrants.iter() {
            let revealed_key = DataKey::Revealed(entrant.clone());
            if let Some(nonce) = env.storage().instance().get::<_, BytesN<32>>(&revealed_key) {
                let nonce_arr = nonce.to_array();
                for i in 0..32 {
                    seed[i] ^= nonce_arr[i];
                }
                revealed_entrants.push_back(entrant);
            }
        }

        if revealed_entrants.is_empty() {
            panic!("no valid reveals");
        }

        let mut index_bytes = [0_u8; 8];
        index_bytes.copy_from_slice(&seed[0..8]);
        let index = (u64::from_be_bytes(index_bytes) % revealed_entrants.len() as u64) as u32;

        let winner = revealed_entrants.get(index).unwrap();

        env.storage().instance().set(&DataKey::Winner, &winner);
        env.storage().instance().set(&DataKey::Drawn, &true);

        env.events()
            .publish((symbol_short!("draw"),), winner.clone());

        winner
    }

    /// Return the drawn winner. Panics if the winner has not been drawn yet.
    pub fn get_winner(env: Env) -> Address {
        env.storage()
            .instance()
            .get(&DataKey::Winner)
            .unwrap_or_else(|| panic!("winner not drawn yet"))
    }
}

