pub fn generate_with_options_layout(
    dir: &Path,
    options: &GenerateOptions,
    layout: TestLayout,
) -> Result<(ContractInfo, Vec<&'static str>)> {
    let info = detect::inspect(dir)?;

    let smoke = build_smoke_test(&info);
    let invariant = build_invariant_test(&info);
    let snapshot = build_snapshot_test(&info);
    let event_test = build_event_test(&info);
    let err_tests = build_error_path_tests(&info);
    let reentry = build_reentrancy_test(&info);
    let init_once = build_init_once_test(&info);
    let ttl_test = build_ttl_test(&info);
    // Empty unless 2+ storage types are used (#232).
    let storage_isolation_test = build_storage_isolation_test(&info);
    // Empty unless the contract exposes an upgrade entrypoint (#234).
    let upgrade_test = build_upgrade_test(&info);
    // Empty unless an entrypoint takes a container argument (#236).
    let roundtrip_test = build_roundtrip_tests(&info);

    let mut files: Vec<(&'static str, String)> = Vec::new();
    match layout {
        TestLayout::Tests => {
            files.push((
                "tests/common/mod.rs",
                format!("{FIXTURES_RS}{}", build_actors_fixture(options.actor_count)),
            ));
            files.push(("tests/forge_smoke.rs", smoke));
            files.push(("tests/forge_invariant.rs", invariant));
            files.push(("tests/forge_snapshots.rs", snapshot));
            if !event_test.is_empty() {
                files.push(("tests/forge_events.rs", event_test));
            }
            if !err_tests.is_empty() {
                files.push(("tests/forge_error_paths.rs", err_tests));
            }
            if !reentry.is_empty() {
                files.push(("tests/forge_reentrancy.rs", reentry));
            }
            if !ttl_test.is_empty() {
                files.push(("tests/forge_ttl.rs", ttl_test));
            }
            if !storage_isolation_test.is_empty() {
                files.push(("tests/forge_storage_isolation.rs", storage_isolation_test));
            }
            if !upgrade_test.is_empty() {
                files.push(("tests/forge_upgrade.rs", upgrade_test));
            }
            if !roundtrip_test.is_empty() {
                files.push(("tests/forge_roundtrip.rs", roundtrip_test));
            }
        }
        TestLayout::Inline => {
            let mut sections: Vec<(&str, String)> = vec![
                ("smoke", smoke),
                ("invariant", invariant),
                ("snapshots", snapshot),
            ];
            if !event_test.is_empty() {
                sections.push(("events", event_test));
            }
            if !err_tests.is_empty() {
                sections.push(("error_paths", err_tests));
            }
            if !reentry.is_empty() {
                sections.push(("reentrancy", reentry));
            }
            if !ttl_test.is_empty() {
                sections.push(("ttl", ttl_test));
            }
            if !storage_isolation_test.is_empty() {
                sections.push(("storage_isolation", storage_isolation_test));
            }
            if !upgrade_test.is_empty() {
                sections.push(("upgrade", upgrade_test));
            }
            if !roundtrip_test.is_empty() {
                sections.push(("roundtrip", roundtrip_test));
            }
            files.push((
                INLINE_MODULE_PATH,
                build_inline_module(&info, &sections, options.actor_count),
            ));
        }
    }

    // Emitted whenever an initialize-style entrypoint exists: a contract that
    // can be re-initialized is a live vulnerability, so the check is not opt-in.
    if !init_once.is_empty() {
        files.push(("tests/forge_init_once.rs", init_once));
    }

    if options.budget {
        let budget_test = build_budget_test(&info, options.budget_entrypoint.as_deref())?;
        if budget_test.is_empty() {
            return Err(ForgeError::InvalidArgument(format!(
                "--budget needs an entrypoint to measure, but no methods were found in {}",
                dir.display()
            )));
        }
        files.push(("tests/forge_budget.rs", budget_test));
    }

    if options.fuzz {
        let mut vars = Vars::new();
        vars.insert("crate_name".into(), info.crate_name.clone());
        files.push(("fuzz/Cargo.toml", render_str(FUZZ_CARGO_TOML, &vars)));
        files.push((
            "fuzz/fuzz_targets/fuzz_target_1.rs",
            generate_fuzz_target(&info),
        ));
    }

    let mut written = Vec::new();
    for (rel, contents) in files {
        let path = dir.join(rel);
        if path.exists() && !options.force {
            return Err(ForgeError::AlreadyExists(path));
        }
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)
                .map_err(ForgeError::io(format!("creating {}", parent.display())))?;
        }
        std::fs::write(&path, contents)
            .map_err(ForgeError::io(format!("writing {}", path.display())))?;
        written.push(rel);
    }

    // The inline module is only compiled once `src/lib.rs` declares it.
    if layout == TestLayout::Inline {
        ensure_inline_module_declared(dir)?;
    }

    Ok((info, written))
}

/// For each of the contract's methods, whether any generated test file
/// references it (issue #231). Scans the written files' contents on disk for
/// `.method_name(` — an approximation, but enough to catch entrypoints no
/// generated file touches at all (e.g. a budget test that only names one of
/// several methods). Returns `(covered, uncovered)` method names, in the
/// order they appear on the contract.
pub fn entrypoint_coverage(
    info: &ContractInfo,
    dir: &Path,
    written: &[&str],
) -> (Vec<String>, Vec<String>) {
    let mut combined = String::new();
    for rel in written {
        if let Ok(contents) = std::fs::read_to_string(dir.join(rel)) {
            combined.push_str(&contents);
            combined.push('\n');
        }
    }

    let mut covered = Vec::new();
    let mut uncovered = Vec::new();
    for m in &info.methods {
        let needle = format!(".{}(", m.name);
        if combined.contains(&needle) {
            covered.push(m.name.clone());
        } else {
            uncovered.push(m.name.clone());
        }
    }
    (covered, uncovered)
}

/// Render the coverage summary printed after generation (issue #231).
/// Empty when the contract has no methods at all.
pub fn format_coverage_summary(covered: &[String], uncovered: &[String]) -> String {
    let total = covered.len() + uncovered.len();
    if total == 0 {
        return String::new();
    }
    let mut out = format!(
        "\ncoverage: {}/{total} entrypoint(s) touched by generated tests\n",
        covered.len()
    );
    if !uncovered.is_empty() {
        out.push_str("no generated test calls: ");
        out.push_str(&uncovered.join(", "));
        out.push('\n');
    }
    out
}

/// Run the generated snapshot tests with `FORGE_UPDATE_SNAPSHOTS=1` (issue
/// #229), so any changed/missing golden file under `tests/snapshots/` is
/// (re)written by [`assert_snapshot`], then report which files changed.
///
/// Returns the relative paths (under `tests/snapshots/`) of files that were
/// added or whose contents changed. Snapshot state is compared before and
/// after running `cargo test --test forge_snapshots`, so a file is only
/// reported when it actually differs — not merely because the test ran.
pub fn update_snapshots(dir: &Path) -> Result<Vec<String>> {
    let snapshots_dir = dir.join("tests/snapshots");
    let before = snapshot_contents(&snapshots_dir);

    let status = std::process::Command::new("cargo")
        .args(["test", "--test", "forge_snapshots"])
        .env("FORGE_UPDATE_SNAPSHOTS", "1")
        .current_dir(dir)
        .status()
        .map_err(ForgeError::io("running `cargo test --test forge_snapshots`".to_string()))?;
    if !status.success() {
        return Err(ForgeError::Other(format!(
            "`cargo test --test forge_snapshots` with FORGE_UPDATE_SNAPSHOTS=1 exited with {status}"
        )));
    }

    let after = snapshot_contents(&snapshots_dir);
    let mut changed: Vec<String> = after
        .iter()
        .filter(|(name, contents)| before.get(*name) != Some(contents))
        .map(|(name, _)| name.clone())
        .collect();
    changed.sort();
    Ok(changed)
}

/// `{filename: contents}` for every `*.snap` file under `dir`, empty when the
/// directory does not exist yet.
fn snapshot_contents(dir: &Path) -> std::collections::HashMap<String, String> {
    let mut map = std::collections::HashMap::new();
    let Ok(entries) = std::fs::read_dir(dir) else {
        return map;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.extension().and_then(|e| e.to_str()) == Some("snap") {
            if let (Some(name), Ok(contents)) = (
                path.file_name().map(|n| n.to_string_lossy().into_owned()),
                std::fs::read_to_string(&path),
            ) {
                map.insert(name, contents);
            }
        }
    }
    map
}

/// Render the report for a generated test harness.
pub fn format_report(info: &ContractInfo, written: &[&str], fuzz: bool) -> String {
    let contract_list = info.contract_types.join(", ");
    let s = if info.contract_types.len() == 1 {
        ""
    } else {
        "s"
    };
    let mut out = format!(
        "generated test harness for contract{s} `{contract_list}` (crate `{}`):\n",
        info.crate_name
    );
    for rel in written {
        out.push_str(&format!("  {rel}\n"));
    }
    if !info.has_testutils {
        out.push_str(
            "\nwarning: dev-dependencies do not enable soroban-sdk's `testutils` feature.\n",
        );
        out.push_str("add this to Cargo.toml or the generated tests will not compile:\n\n");
        out.push_str("  [dev-dependencies]\n");
        out.push_str("  soroban-sdk = { version = \"*\", features = [\"testutils\"] }\n");
    }
    if !info.has_proptest {
        out.push_str("\nwarning: dev-dependencies do not include `proptest`.\n");
        out.push_str(
            "add this to Cargo.toml or the generated invariant tests will not compile:\n\n",
        );
        out.push_str("  [dev-dependencies]\n");
        out.push_str("  proptest = \"1.6\"\n");
    }
    if info.has_constructor {
        out.push_str(&format!(
            "\nnote: `{}` has a __constructor; real arguments were generated in the smoke test. Review and adjust them as needed.\n",
            info.contract_types.join(", ")
        ));
    }
    if info.has_token_deps {
        out.push_str("\nnote: Stellar Asset Contract (SAC) token usage detected.\n");
        out.push_str("token fixture helpers (`setup_token`, `register_*`) were generated in the\n");
        out.push_str("smoke test's `token_fixtures` module. Use `common::create_token` and\n");
        out.push_str("`common::fund` to mint test balances before calling contract methods.\n");
    }
    if !info.events.is_empty() {
        out.push_str(&format!(
            "\nnote: {} event(s) detected via `env.events().publish(...)`.\n",
            info.events.len()
        ));
        out.push_str("event tests were generated in tests/forge_events.rs — review and customise the assertions.\n");
    }
    if info.has_persistent_storage {
        out.push_str("\nnote: persistent storage detected.\n");
        out.push_str("TTL / rent-extension tests were generated — they bump a scratch entry with\n");
        out.push_str("`extend_ttl` and assert it survives a ledger advance. Point them at your\n");
        out.push_str("real `DataKey` to guard against rent regressions.\n");
    }
    if info.has_contractevent {
        out.push_str("\nnote: `#[contractevent]` attribute(s) found in the contract source.\n");
        out.push_str("these define strongly-typed events; the generated event tests cover `env.events().publish(...)` calls.\n");
    }
    if let Some(init) = &info.init_method {
        out.push_str(&format!(
            "\nnote: `{}` looks like a one-time setup entrypoint.\n",
            init.name
        ));
        out.push_str("tests/forge_init_once.rs asserts a second call is rejected. If it fails,\n");
        out.push_str("the contract has no re-initialization guard — that is a real finding, not\n");
        out.push_str("a bad test.\n");
    }
    if written.contains(&"tests/forge_budget.rs") {
        out.push_str("\nnote: the budget test starts at Soroban's per-transaction limits.\n");
        out.push_str("see the real cost with: cargo test --test forge_budget -- --nocapture\n");
        out.push_str(
            "then tighten MAX_CPU_INSTRUCTIONS / MAX_MEMORY_BYTES to catch regressions.\n",
        );
    }
    if fuzz {
        out.push_str("\nrun the fuzzer with: cargo +nightly fuzz run fuzz_target_1\n");
    } else {
        out.push_str("\nrun them with: cargo test\n");
    }
    out
}

/// [`format_report`] plus a note about where the tests landed.
pub fn format_report_with_layout(
    info: &ContractInfo,
    written: &[&str],
    fuzz: bool,
    layout: TestLayout,
) -> String {
    let mut out = format_report(info, written, fuzz);
    if layout == TestLayout::Inline {
        out.push_str(&format!(
            "\nnote: inline layout — tests live in `{INLINE_MODULE_PATH}` and `src/lib.rs`\n\
             now declares `#[cfg(test)] mod {INLINE_MODULE_NAME};`.\n\
             Re-run with `--layout tests` for a `tests/` integration-test directory instead.\n"
        ));
    }
    out
}

/// Render the aggregated report for a workspace test-init run.
pub fn format_workspace_report(results: &[MemberHarness], fuzz: bool) -> String {
    let mut out = String::from("generated test harnesses for workspace members:\n\n");
    for r in results {
        match &r.outcome {
            Ok((info, written)) => {
                out.push_str(&format!("  {} (crate `{}`):\n", r.member, info.crate_name));
                for rel in written {
                    out.push_str(&format!("    {rel}\n"));
                }
            }
            Err(reason) => {
                out.push_str(&format!("  {} — skipped: {reason}\n", r.member));
            }
        }
    }
    let ok = results.iter().filter(|r| r.outcome.is_ok()).count();
    let skipped = results.len() - ok;
    out.push_str(&format!(
        "\n{ok} member(s) got a harness, {skipped} skipped.\n"
    ));
    if fuzz {
        out.push_str("run a member fuzzer with: cargo +nightly fuzz run fuzz_target_1\n");
    } else {
        out.push_str("run them with: cargo test\n");
    }
    out
}

