/// Render the `tests/forge_events.rs` content for all `#[contract]` structs found.
/// Only emits content when the contract has detected events.
pub fn build_event_test(info: &ContractInfo) -> String {
    if info.events.is_empty() {
        return String::new();
    }

    let mut out = String::from(EVENT_TEST_RS);

    let mut use_parts: Vec<String> = Vec::new();
    for ct in &info.contract_types {
        use_parts.push(ct.clone());
        use_parts.push(format!("{ct}Client"));
    }
    out.push_str(&format!(
        "use {}::{{ {} }};\n",
        info.crate_name,
        use_parts.join(", ")
    ));

    // Group events by method name for per-method test generation.
    let mut method_events: std::collections::BTreeMap<&str, Vec<&detect::EventInfo>> =
        std::collections::BTreeMap::new();
    for event in &info.events {
        method_events
            .entry(event.method.as_str())
            .or_default()
            .push(event);
    }

    for ct in &info.contract_types {
        for (method_name, events) in &method_events {
            let mut vars = Vars::new();
            vars.insert("contract_type".into(), ct.clone());
            vars.insert("fn_name".into(), to_snake_case(ct));
            vars.insert("contract_args".into(), info.constructor_args.clone());

            let mut event_tests = String::new();
            event_tests.push_str(&format!(
                "    client.{}({});\n",
                method_name,
                generate_default_method_call_args(info, method_name)
            ));
            event_tests.push_str("    let events = env.events().all();\n");
            event_tests
                .push_str("    assert!(!events.is_empty(), \"expected at least one event\");\n\n");

            for (idx, event) in events.iter().enumerate() {
                event_tests.push_str(&format!(
                    "    // Assert on emitted event from `{}`\n",
                    method_name
                ));
                event_tests.push_str(&format!("    // Topics: {}\n", event.topics.join(", ")));
                if let Some(data) = &event.data {
                    event_tests.push_str(&format!("    // Data: {data}\n"));
                }
                event_tests.push_str(&format!("    let event_{idx} = &events[{idx}];\n"));
                event_tests.push_str(&format!(
                    "    assert!(!event_{idx}.topics.is_empty(), \"event should have topics\");\n"
                ));
                event_tests.push('\n');
            }

            vars.insert("event_tests".into(), event_tests);
            out.push_str(&render_str(EVENT_TEST_FN, &vars));
        }
    }

    out
}

/// Render a method's arguments as a client call list.
///
/// Contract clients take every argument by reference (`client.mint(&to,
/// &amount)`), so each default from [`detect::map_type_to_default`] is
/// borrowed.
fn client_call_args(method: &detect::MethodInfo) -> String {
    method
        .args
        .iter()
        .map(|(_, ty)| format!("&{}", detect::map_type_to_default(ty)))
        .collect::<Vec<_>>()
        .join(", ")
}

/// Render the `tests/forge_budget.rs` content: a benchmark that measures one
/// entrypoint with `env.cost_estimate().budget()` and asserts an upper bound.
///
/// `entrypoint` names the method to measure; `None` picks the contract's first
/// detected entrypoint. Returns an empty string when the contract exports no
/// methods at all, following the same "no content, no file" convention as
/// [`build_event_test`].
pub fn build_budget_test(info: &ContractInfo, entrypoint: Option<&str>) -> Result<String> {
    let method = match entrypoint {
        Some(name) => info
            .methods
            .iter()
            .find(|m| m.name == name)
            .ok_or_else(|| {
                ForgeError::InvalidArgument(format!(
                    "`{name}` is not an entrypoint of `{}` (found: {})",
                    info.contract_types.join(", "),
                    if info.methods.is_empty() {
                        "none".to_string()
                    } else {
                        info.methods
                            .iter()
                            .map(|m| m.name.as_str())
                            .collect::<Vec<_>>()
                            .join(", ")
                    }
                ))
            })?,
        None => match info.methods.first() {
            Some(m) => m,
            None => return Ok(String::new()),
        },
    };

    let mut out = String::from(BUDGET_TEST_RS);
    out.push_str(&format!(
        "use {}::{{ {} }};\n",
        info.crate_name,
        contract_use_list(info)
    ));
    out.push_str(BUDGET_LIMITS);

    for ct in &info.contract_types {
        let mut vars = Vars::new();
        vars.insert("contract_type".into(), ct.clone());
        vars.insert("fn_name".into(), to_snake_case(ct));
        vars.insert("contract_args".into(), info.constructor_args.clone());
        vars.insert("entrypoint".into(), method.name.clone());
        vars.insert("entrypoint_args".into(), client_call_args(method));
        out.push_str(&render_str(BUDGET_TEST_FN, &vars));
    }

    Ok(out)
}

