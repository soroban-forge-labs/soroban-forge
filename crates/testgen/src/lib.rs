    #[test]
    fn inline_layout_writes_a_single_module_and_declares_it() {
        let tmp = tempfile::tempdir().unwrap();
        let dir = tmp.path().join("demo");
        hello_world_project(&dir);

        let (_info, written) =
            generate_with_layout(&dir, true, false, TestLayout::Inline, false, None).unwrap();
        assert_eq!(written, vec!["src/forge_tests.rs"]);
        assert!(!dir.join("tests/forge_smoke.rs").exists());

        let lib = std::fs::read_to_string(dir.join("src/lib.rs")).unwrap();
        assert!(lib.contains("#[cfg(test)]\nmod forge_tests;"), "{lib}");

        let inline = std::fs::read_to_string(dir.join("src/forge_tests.rs")).unwrap();
        // Fixtures and every test area end up as submodules of one file.
        assert!(inline.contains("pub mod common {"));
        assert!(inline.contains("mod smoke {"));
        assert!(inline.contains("mod invariant {"));
        assert!(inline.contains("mod snapshots {"));
        // Rewritten for in-crate use: no `mod common;`, no external crate path.
        assert!(!inline.contains("mod common;"));
        assert!(inline.contains("use super::common;"));
        assert!(inline.contains("use crate::{ HelloContract, HelloContractClient };"));
        assert!(!inline.contains("use demo::"));
        // `#![no_std]` contracts still need std for the fixtures.
        assert!(inline.contains("extern crate std;"));
        // Section doc comments are demoted: an inner doc comment may not
        // follow the submodule's own inner attributes.
        assert!(inline
            .contains("// Generated by `soroban-forge test-init`. Grow it into your real test suite."));
        assert!(!inline.contains("//! Generated by `soroban-forge test-init`. Grow it"));
        assert!(!inline.contains("{{"));
    }

