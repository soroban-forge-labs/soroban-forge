/// Render the `fuzz/fuzz_targets/fuzz_target_1.rs` content.
///
/// The fuzz target exercises the first detected `#[contract]` type: it derives
/// an `Arbitrary` `FuzzInput` enum over the contract's methods and, when the
/// contract has a `__constructor`, a `FuzzConstructorArgs` struct for its
/// arguments.
pub fn generate_fuzz_target(info: &ContractInfo) -> String {
    let contract_type = info
        .contract_types
        .first()
        .map(String::as_str)
        .unwrap_or("Contract");

    let mut out = String::new();
    out.push_str("#![no_main]\n");
    out.push_str("use libfuzzer_sys::fuzz_target;\n");
    out.push_str("use arbitrary::Arbitrary;\n");
    out.push_str("use soroban_sdk::testutils::arbitrary::SorobanArbitrary;\n");
    out.push_str("use soroban_sdk::{Env, Address, String, MuxedAddress, IntoVal, TryFromVal};\n");
    out.push_str(&format!(
        "use {}::{{{}, {}Client}};\n\n",
        info.crate_name, contract_type, contract_type
    ));

    if let Some(constructor_args) = &info.constructor_arg_types {
        out.push_str("#[derive(Arbitrary, Debug)]\n");
        out.push_str("pub struct FuzzConstructorArgs {\n");
        for (arg, ty) in constructor_args {
            out.push_str(&format!(
                "    {}: <{} as SorobanArbitrary>::Prototype,\n",
                arg, ty
            ));
        }
        out.push_str("}\n\n");
    }

    out.push_str("#[derive(Arbitrary, Debug)]\n");
    out.push_str("pub enum FuzzInput {\n");
    for m in &info.methods {
        out.push_str(&format!("    {}{{\n", m.name));
        for (arg, ty) in &m.args {
            out.push_str(&format!(
                "        {}: <{} as SorobanArbitrary>::Prototype,\n",
                arg, ty
            ));
        }
        out.push_str("    },\n");
    }
    out.push_str("}\n\n");

    if info.constructor_arg_types.is_some() {
        out.push_str("fuzz_target!(|input: (FuzzConstructorArgs, FuzzInput)| {\n");
        out.push_str("    let (constr, method_input) = input;\n");
    } else {
        out.push_str("fuzz_target!(|method_input: FuzzInput| {\n");
    }

    out.push_str("    let env = Env::default();\n");
    out.push_str("    env.mock_all_auths();\n");

    if let Some(constructor_args) = &info.constructor_arg_types {
        for (arg, ty) in constructor_args {
            out.push_str(&format!(
                "    let Ok(constr_{}) = {}::try_from_val(&env, &constr.{}) else {{ return; }};\n",
                arg, ty, arg
            ));
        }
        let constr_call_args = constructor_args
            .iter()
            .map(|(n, _)| format!("constr_{}", n))
            .collect::<Vec<_>>()
            .join(", ");
        out.push_str(&format!(
            "    let contract_id = env.register({}, ({}));\n",
            contract_type, constr_call_args
        ));
        out.push_str(&format!(
            "    let client = {}Client::new(&env, &contract_id);\n",
            contract_type
        ));
    } else {
        out.push_str(&format!(
            "    let contract_id = env.register({}, ());\n",
            contract_type
        ));
        out.push_str(&format!(
            "    let client = {}Client::new(&env, &contract_id);\n",
            contract_type
        ));
    }

    out.push_str("\n    match method_input {\n");
    for m in &info.methods {
        out.push_str(&format!("        FuzzInput::{} {{ ", m.name));
        let args_list: Vec<String> = m.args.iter().map(|(n, _)| n.clone()).collect();
        out.push_str(&args_list.join(", "));
        out.push_str(" } => {\n");
        for (arg, ty) in &m.args {
            out.push_str(&format!(
                "            let Ok(arg_{}) = {}::try_from_val(&env, &{}) else {{ return; }};\n",
                arg, ty, arg
            ));
        }
        out.push_str(&format!("            let _ = client.{}(", m.name));
        let call_args: Vec<String> = m.args.iter().map(|(n, _)| format!("&arg_{}", n)).collect();
        out.push_str(&call_args.join(", "));
        out.push_str(");\n        },\n");
    }
    out.push_str("    }\n");
    out.push_str("});\n");
    out
}

/// Where `test-init` puts the generated tests.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum TestLayout {
    /// One file per concern under the `tests/` integration-test directory.
    #[default]
    Tests,
    /// A single `#[cfg(test)] mod forge_tests` compiled as part of the crate.
    Inline,
}

impl TestLayout {
    /// Parse the `--layout` value.
    pub fn parse(value: &str) -> Result<Self> {
        match value {
            "tests" | "integration" => Ok(Self::Tests),
            "inline" => Ok(Self::Inline),
            other => Err(ForgeError::InvalidArgument(format!(
                "unknown layout `{other}` (expected `tests` or `inline`)"
            ))),
        }
    }

    /// Canonical name, as accepted by `--layout`.
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Tests => "tests",
            Self::Inline => "inline",
        }
    }
}

/// Path of the inline test module, relative to the project root.
pub const INLINE_MODULE_PATH: &str = "src/forge_tests.rs";
/// Name the inline test module is declared under in `src/lib.rs`.
pub const INLINE_MODULE_NAME: &str = "forge_tests";

/// Rewrite a `tests/`-style file body so it works as a submodule *inside* the
/// crate: `mod common;` becomes `use super::common;`, `use <crate>::` becomes
/// `use crate::`, and inner doc comments become plain comments (they may not
/// follow the module's own inner attributes).
fn inline_body(contents: &str, crate_name: &str) -> String {
    contents
        .replace("mod common;", "use super::common;")
        .replace(&format!("use {crate_name}::"), "use crate::")
        .replace("//!", "//")
}

/// Build the single `src/forge_tests.rs` file for [`TestLayout::Inline`].
///
/// `sections` are `(module_name, tests/-style file body)` pairs. Each becomes a
/// submodule alongside a shared `common` fixtures module. `extern crate std;`
/// (plus the `format!` import) is declared per module so the harness also
/// compiles inside `#![no_std]` contract crates.
pub fn build_inline_module(info: &ContractInfo, sections: &[(&str, String)], actor_count: usize) -> String {
    let mut out = String::new();
    out.push_str("//! Generated by `soroban-forge test-init --layout inline`.\n");
    out.push_str("//!\n");
    out.push_str("//! Declared from `src/lib.rs` as `#[cfg(test)] mod forge_tests;`, so nothing\n");
    out.push_str("//! here is compiled outside `cargo test`.\n\n");

    let fixtures = format!("{FIXTURES_RS}{}", build_actors_fixture(actor_count))
        .replace("#![allow(dead_code)] // generated fixtures\n", "")
        .replace("//!", "//");
    out.push_str("pub mod common {\n");
    out.push_str("#![allow(dead_code)]\n");
    // `#![no_std]` crates have neither `std` paths nor `format!` in scope.
    out.push_str("extern crate std;\n");
    out.push_str("use std::format;\n\n");
    out.push_str(&fixtures);
    out.push_str("}\n");

    for (name, body) in sections {
        out.push_str(&format!("\nmod {name} {{\n"));
        out.push_str("#![allow(unused_imports)]\n");
        out.push_str("extern crate std;\n\n");
        out.push_str(&inline_body(body, &info.crate_name));
        out.push_str("}\n");
    }

    out
}

/// Declare the inline test module in `src/lib.rs` if it is not there already.
/// Returns whether the declaration was appended.
pub fn ensure_inline_module_declared(dir: &Path) -> Result<bool> {
    let lib_path = dir.join("src/lib.rs");
    let mut source = std::fs::read_to_string(&lib_path)
        .map_err(ForgeError::io(format!("reading {}", lib_path.display())))?;
    if source.contains(&format!("mod {INLINE_MODULE_NAME};")) {
        return Ok(false);
    }
    if !source.ends_with('\n') {
        source.push('\n');
    }
    source.push_str(&format!("\n#[cfg(test)]\nmod {INLINE_MODULE_NAME};\n"));
    std::fs::write(&lib_path, source)
        .map_err(ForgeError::io(format!("writing {}", lib_path.display())))?;
    Ok(true)
}

/// True when `dir/Cargo.toml` declares a `[workspace]` table.
pub fn is_workspace(dir: &Path) -> bool {
    let manifest = dir.join("Cargo.toml");
    match std::fs::read_to_string(&manifest) {
        Ok(raw) => raw
            .parse::<toml::Table>()
            .map(|t| t.contains_key("workspace"))
            .unwrap_or(false),
        Err(_) => false,
    }
}

/// Resolve the member crate directories of the workspace rooted at `dir` by
/// reading `[workspace].members` and expanding trailing `/*` globs against the
/// filesystem. Only directories that actually contain a `Cargo.toml` are
/// returned, sorted for a stable report order.
pub fn workspace_members(dir: &Path) -> Result<Vec<std::path::PathBuf>> {
    let manifest = dir.join("Cargo.toml");
    let raw = std::fs::read_to_string(&manifest)
        .map_err(ForgeError::io(format!("reading {}", manifest.display())))?;
    let table: toml::Table = raw.parse().map_err(|e| ForgeError::Config {
        path: manifest.clone(),
        message: format!("{e}"),
    })?;

    let members = table
        .get("workspace")
        .and_then(|w| w.get("members"))
        .and_then(|m| m.as_array())
        .map(|arr| {
            arr.iter()
                .filter_map(|v| v.as_str().map(String::from))
                .collect::<Vec<_>>()
        })
        .unwrap_or_default();

    let mut dirs = Vec::new();
    for pattern in members {
        if let Some(prefix) = pattern.strip_suffix("/*") {
            let base = dir.join(prefix);
            if let Ok(entries) = std::fs::read_dir(&base) {
                for entry in entries.flatten() {
                    let p = entry.path();
                    if p.join("Cargo.toml").is_file() {
                        dirs.push(p);
                    }
                }
            }
        } else {
            let p = dir.join(&pattern);
            if p.join("Cargo.toml").is_file() {
                dirs.push(p);
            }
        }
    }
    dirs.sort();
    Ok(dirs)
}

/// Per-member result of a workspace test-init run.
pub struct MemberHarness {
    pub member: String,
    pub outcome: std::result::Result<(ContractInfo, Vec<&'static str>), String>,
}

/// What `test-init` should emit, beyond the always-on harness files.
#[derive(Debug, Clone)]
pub struct GenerateOptions {
    /// Overwrite files that already exist.
    pub force: bool,
    /// Also emit a cargo-fuzz target under `fuzz/`.
    pub fuzz: bool,
    /// Also emit `tests/forge_budget.rs`.
    pub budget: bool,
    /// Entrypoint the budget test should measure. `None` picks the first
    /// detected one. Ignored unless `budget` is set.
    pub budget_entrypoint: Option<String>,
    /// Number of identities in the generated multi-user fixture (#230).
    pub actor_count: usize,
    /// Turn a missing-coverage warning into a non-zero exit (#231).
    pub fail_on_uncovered: bool,
}

impl Default for GenerateOptions {
    fn default() -> Self {
        Self {
            force: false,
            fuzz: false,
            budget: false,
            budget_entrypoint: None,
            actor_count: DEFAULT_ACTOR_COUNT,
            fail_on_uncovered: false,
        }
    }
}

impl GenerateOptions {
    /// The options the two-bool legacy signatures correspond to.
    pub fn new(force: bool, fuzz: bool) -> Self {
        Self {
            force,
            fuzz,
            ..Self::default()
        }
    }
}

/// Generate a harness for every member of the workspace at `dir`. Members that
/// cannot be inspected (no `#[contract]`, missing `src/lib.rs`, etc.) are
/// skipped and reported, rather than failing the whole run.
pub fn generate_workspace(dir: &Path, force: bool, fuzz: bool) -> Result<Vec<MemberHarness>> {
    generate_workspace_with(dir, &GenerateOptions::new(force, fuzz))
}

/// [`generate_workspace`] with the full option set.
pub fn generate_workspace_with(
    dir: &Path,
    options: &GenerateOptions,
) -> Result<Vec<MemberHarness>> {
    generate_workspace_with_layout(dir, options.force, options.fuzz, TestLayout::default())
}

/// [`generate_workspace`] with an explicit test layout.
pub fn generate_workspace_with_layout(
    dir: &Path,
    force: bool,
    fuzz: bool,
    layout: TestLayout,
) -> Result<Vec<MemberHarness>> {
    let members = workspace_members(dir)?;
    if members.is_empty() {
        return Err(ForgeError::InvalidArgument(format!(
            "no workspace members with a Cargo.toml found under {}",
            dir.display()
        )));
    }

    let mut results = Vec::new();
    for member_dir in members {
        let rel = member_dir
            .strip_prefix(dir)
            .unwrap_or(&member_dir)
            .to_string_lossy()
            .into_owned();
        let outcome = match generate_with_layout(&member_dir, force, fuzz, layout, false, None) {
            Ok(pair) => Ok(pair),
            Err(e) => Err(e.to_string()),
        };
        results.push(MemberHarness {
            member: rel,
            outcome,
        });
    }
    Ok(results)
}

/// Generate the harness into `dir`. Public API behind `test-init`.
/// Returns the list of files written (relative to `dir`). With `fuzz`, also
/// emits a cargo-fuzz target under `fuzz/`.
/// Build error-path tests (#97).
pub fn build_error_path_tests(info: &ContractInfo) -> String {
    let mut out = String::from("//! Error-path tests.\n//! Generated by soroban-forge test-init.\n\n");
    for ct in &info.contract_types {
        let snake = to_snake_case(ct);
        out.push_str(&format!("use {}::*;\n", info.crate_name));
        out.push_str("use soroban_sdk::testutils::Address as _;\n");
        out.push_str("use soroban_sdk::Env;\n\n");
        for m in &info.methods {
            out.push_str(&format!("#[test]\nfn {snake}_{}_error_path() {{\n", m.name));
            out.push_str("    let env = Env::default();\n");
            out.push_str("    env.mock_all_auths();\n");
            out.push_str(&format!("    let id = env.register({ct}, ());\n"));
            out.push_str(&format!("    let client = {ct}Client::new(&env, &id);\n"));
            out.push_str(&format!("    let _r = client.try_{}(", m.name));
            for (i, (_, ty)) in m.args.iter().enumerate() {
                if i > 0 { out.push_str(", "); }
                match ty.as_str() {
                    "i128" | "i64" | "i32" | "u64" | "u32" => out.push_str("&0"),
                    "bool" => out.push_str("&false"),
                    _ => out.push_str("&soroban_sdk::Address::generate(&env)"),
                }
            }
            out.push_str(");\n}\n\n");
        }
    }
    out
}

/// Build reentrancy smoke test (#98).
pub fn build_reentrancy_test(info: &ContractInfo) -> String {
    let mut out = String::from("//! Reentrancy-safety smoke test.\n");
    out.push_str("//! Soroban prevents recursive cross-contract calls.\n");
    out.push_str("//! This test documents the consideration.\n");
    out.push_str("//! Generated by soroban-forge test-init.\n\n");
    for ct in &info.contract_types {
        let snake = to_snake_case(ct);
        out.push_str(&format!("use {}::*;\n", info.crate_name));
        out.push_str("use soroban_sdk::testutils::Address as _;\n");
        out.push_str("use soroban_sdk::Env;\n\n");
        out.push_str(&format!("#[test]\nfn {snake}_no_state_leakage_between_instances() {{\n"));
        out.push_str("    let env = Env::default();\n");
        out.push_str("    env.mock_all_auths();\n");
        out.push_str(&format!("    let a = env.register({ct}, ());\n"));
        out.push_str(&format!("    let b = env.register({ct}, ());\n"));
        out.push_str("    assert_ne!(a, b);\n");
        out.push_str("}\n\n");
    }
    out
}

