/// Write the criterion bench target into `dir/benches/forge_bench.rs` and add
/// the `[[bench]]` section to the project's `Cargo.toml` (#235).
///
/// Returns the files touched, relative to `dir`. `Cargo.toml` is only listed
/// when it actually changed — re-running `--bench` leaves an already-declared
/// target alone rather than appending a duplicate section.
pub fn write_bench_files(dir: &Path, info: &ContractInfo, force: bool) -> Result<Vec<&'static str>> {
    let contents = build_bench(info);
    if contents.is_empty() {
        return Err(ForgeError::InvalidArgument(format!(
            "--bench found no entrypoints to benchmark in {}",
            dir.display()
        )));
    }

    let mut written = Vec::new();

    let rel = "benches/forge_bench.rs";
    let path = dir.join(rel);
    if path.exists() && !force {
        return Err(ForgeError::AlreadyExists(path));
    }
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)
            .map_err(ForgeError::io(format!("creating {}", parent.display())))?;
    }
    std::fs::write(&path, contents)
        .map_err(ForgeError::io(format!("writing {}", path.display())))?;
    written.push(rel);

    // Without the `[[bench]]` target and the criterion dev-dependency,
    // `cargo bench` never picks the file up.
    let manifest_path = dir.join("Cargo.toml");
    let manifest = std::fs::read_to_string(&manifest_path)
        .map_err(ForgeError::io(format!("reading {}", manifest_path.display())))?;
    if let Some(updated) = ensure_bench_target(&manifest) {
        std::fs::write(&manifest_path, updated)
            .map_err(ForgeError::io(format!("writing {}", manifest_path.display())))?;
        written.push("Cargo.toml");
    }

    Ok(written)
}

/// Write the coverage script into `dir/scripts/coverage.sh`.
pub fn write_coverage_script(dir: &Path, force: bool) -> Result<&'static str> {
    let rel = "scripts/coverage.sh";
    let path = dir.join(rel);
    if path.exists() && !force {
        return Err(ForgeError::AlreadyExists(path));
    }
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)
            .map_err(ForgeError::io(format!("creating {}", parent.display())))?;
    }
    std::fs::write(&path, COVERAGE_SCRIPT)
        .map_err(ForgeError::io(format!("writing {}", path.display())))?;
    // Make the script executable on Unix.
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let perms = std::fs::Permissions::from_mode(0o755);
        std::fs::set_permissions(&path, perms).map_err(ForgeError::io(format!(
            "setting permissions on {}",
            path.display()
        )))?;
    }
    Ok(rel)
}

/// Convert `CamelCase` struct names to `snake_case` test function names.
pub fn to_snake_case(s: &str) -> String {
    let mut out = String::new();
    for (i, c) in s.chars().enumerate() {
        if c.is_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.extend(c.to_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}

/// Render the `tests/forge_smoke.rs` content for all `#[contract]` structs found.
pub fn build_smoke_test(info: &ContractInfo) -> String {
    let mut out = String::from(SMOKE_TEST_RS);

    let mut use_parts: Vec<String> = Vec::new();
    for ct in &info.contract_types {
        use_parts.push(ct.clone());
        use_parts.push(format!("{ct}Client"));
    }
    out.push_str(&format!(
        "use {}::{{ {} }};\n",
        info.crate_name,
        use_parts.join(", ")
    ));

    for ct in &info.contract_types {
        let mut vars = Vars::new();
        vars.insert("contract_type".into(), ct.clone());
        vars.insert("fn_name".into(), to_snake_case(ct));
        vars.insert("contract_args".into(), info.constructor_args.clone());

        // When the contract has SAC token dependencies, emit fixture setup code
        // that registers a Stellar Asset Contract and mints a test balance.
        if info.has_token_deps {
            let token_fixture = build_token_fixture(info);
            out.push_str(&token_fixture);
        }

        out.push_str(&render_str(SMOKE_TEST_FN, &vars));
    }

    out
}

/// Build SAC token fixture setup code for contracts that accept token addresses.
///
/// When the contract source uses `TokenClient`, `StellarAssetClient`, or has
/// constructor/method parameters named like `token*` / `asset*` typed as
/// `Address`, this code is prepended to the smoke test so the tester can
/// immediately mint balances and pass the SAC address to the contract.
