//! Token vesting with cliff + linear release schedule.
//!
//! Tokens are locked in the contract and become claimable by a beneficiary
//! over time according to a configurable vesting schedule:
//!
//! * **Cliff** — no tokens are claimable until a duration (in seconds) has
//!   passed since the contract was initialized.
//! * **Linear release** — after the cliff, tokens vest continuously at a
//!   constant rate over the remaining vesting duration.
//! * **Claim** — the beneficiary may call `claim` at any point; the contract
//!   transfers the newly vested amount since the last claim.
//!
//! Generated by [soroban-forge](https://github.com/soroban-forge-labs/soroban-forge).

#![no_std]

use soroban_sdk::{
    contract, contracterror, contractevent, contractimpl, contracttype, panic_with_error, symbol_short, token, Address, Env,
};

#[contracterror]
#[derive(Copy, Clone, Debug, Eq, PartialEq)]
#[repr(u32)]
pub enum Error {
    AlreadyInitialized = 1,
    TotalAmountMustBePositive = 2,
    AlreadyFunded = 3,
    AlreadyRevoked = 4,
    NothingToClaim = 5,
}

/// Ledgers per day, assuming ~5s per ledger.
pub const DAY_IN_LEDGERS: u32 = 17_280;
/// Instance storage TTL (30 days). The whole schedule (admin, token,
/// beneficiary, timestamps, amounts) lives in instance storage, so it is bumped
/// on every state-changing call to keep the contract from being archived.
pub const INSTANCE_TTL: u32 = 30 * DAY_IN_LEDGERS;
/// Threshold at which a state-changing call extends the instance TTL.
pub const INSTANCE_TTL_THRESHOLD: u32 = INSTANCE_TTL - DAY_IN_LEDGERS;

fn extend_instance_ttl(env: &Env) {
    env.storage()
        .instance()
        .extend_ttl(INSTANCE_TTL_THRESHOLD, INSTANCE_TTL);
}

#[contracttype]
pub enum DataKey {
    Admin,
    PendingAdmin,
    Token,
    Beneficiary,
    Start,
    Cliff,
    End,
    TotalAmount,
    Claimed,
    Funded,
    Revoked,
}

/// Emitted when the admin proposes a successor.
#[contractevent]
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct AdminProposed {
    #[topic]
    pub admin: Address,
    pub new_admin: Address,
}

/// Emitted when the pending admin accepts and becomes admin.
#[contractevent]
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct AdminAccepted {
    #[topic]
    pub old_admin: Address,
    pub new_admin: Address,
}

/// Emitted when the admin cancels a pending proposal.
#[contractevent]
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct AdminProposalCancelled {
    #[topic]
    pub admin: Address,
    pub pending: Address,
}

#[contract]
pub struct VestingContract;

#[contractimpl]
impl VestingContract {
    /// Initialize the vesting schedule.
    ///
    /// * `admin` — address that will fund the contract with tokens
    /// * `token` — contract address of the SEP-41 token to vest
    /// * `beneficiary` — address that receives vested tokens
    /// * `cliff_duration` — seconds from now until first tokens vest
    /// * `vesting_duration` — seconds from cliff end until fully vested
    /// * `total_amount` — total tokens to vest over the schedule
    pub fn __constructor(
        env: Env,
        admin: Address,
        token: Address,
        beneficiary: Address,
        cliff_duration: u64,
        vesting_duration: u64,
        total_amount: i128,
    ) {
        extend_instance_ttl(&env);

        if total_amount <= 0 {
            panic_with_error!(&env, Error::TotalAmountMustBePositive);
        }

        let now = env.ledger().timestamp();

        env.storage().instance().set(&DataKey::Admin, &admin);
        env.storage().instance().set(&DataKey::Token, &token);
        env.storage()
            .instance()
            .set(&DataKey::Beneficiary, &beneficiary);
        env.storage().instance().set(&DataKey::Start, &now);
        env.storage()
            .instance()
            .set(&DataKey::Cliff, &(now + cliff_duration));
        env.storage()
            .instance()
            .set(&DataKey::End, &(now + cliff_duration + vesting_duration));
        env.storage()
            .instance()
            .set(&DataKey::TotalAmount, &total_amount);
        env.storage().instance().set(&DataKey::Claimed, &0_i128);
        env.storage().instance().set(&DataKey::Funded, &false);
        env.storage().instance().set(&DataKey::Revoked, &false);
    }

    /// Deposit the full vesting amount into this contract.
    ///
    /// Must be called once by the `admin` after `initialize`.
    pub fn fund(env: Env) {
        let admin: Address = env.storage().instance().get(&DataKey::Admin).unwrap();
        admin.require_auth();
        extend_instance_ttl(&env);

        if env
            .storage()
            .instance()
            .get::<_, bool>(&DataKey::Funded)
            .unwrap_or(false)
        {
            panic_with_error!(&env, Error::AlreadyFunded);
        }
        env.storage().instance().set(&DataKey::Funded, &true);

        let token: Address = env.storage().instance().get(&DataKey::Token).unwrap();
        let total_amount: i128 = env.storage().instance().get(&DataKey::TotalAmount).unwrap();

        let client = token::Client::new(&env, &token);
        client.transfer(&admin, &env.current_contract_address(), &total_amount);

        env.events()
            .publish((symbol_short!("fund"), admin), total_amount);
    }

    /// Revoke unvested tokens and return them to the `admin`, leaving already
    /// vested tokens claimable by the beneficiary.
    pub fn revoke(env: Env) -> i128 {
        let admin: Address = env.storage().instance().get(&DataKey::Admin).unwrap();
        admin.require_auth();
        extend_instance_ttl(&env);

        if env
            .storage()
            .instance()
            .get::<_, bool>(&DataKey::Revoked)
            .unwrap_or(false)
        {
            panic_with_error!(&env, Error::AlreadyRevoked);
        }

        let vested = Self::get_vested_amount(env.clone());
        let total_amount: i128 = env.storage().instance().get(&DataKey::TotalAmount).unwrap();
        let unvested = total_amount - vested;

        env.storage().instance().set(&DataKey::Revoked, &true);
        env.storage()
            .instance()
            .set(&DataKey::TotalAmount, &vested);
        env.storage()
            .instance()
            .set(&DataKey::End, &env.ledger().timestamp());

        if env
            .storage()
            .instance()
            .get::<_, bool>(&DataKey::Funded)
            .unwrap_or(false)
            && unvested > 0
        {
            let token: Address = env.storage().instance().get(&DataKey::Token).unwrap();
            let client = token::Client::new(&env, &token);
            client.transfer(&env.current_contract_address(), &admin, &unvested);
        }

        env.events()
            .publish((symbol_short!("revoke"), admin), unvested);

        unvested
    }

    /// Return the current admin.
    pub fn admin(env: Env) -> Address {
        env.storage().instance().get(&DataKey::Admin).unwrap()
    }

    /// Return the pending admin, if a handover has been proposed.
    pub fn pending_admin(env: Env) -> Option<Address> {
        env.storage().instance().get(&DataKey::PendingAdmin)
    }

    /// Step one of a handover: the current admin nominates `new_admin`.
    pub fn propose_admin(env: Env, new_admin: Address) {
        let admin: Address = env.storage().instance().get(&DataKey::Admin).unwrap();
        admin.require_auth();
        extend_instance_ttl(&env);
        env.storage()
            .instance()
            .set(&DataKey::PendingAdmin, &new_admin);
        AdminProposed { admin, new_admin }.publish(&env);
    }

    /// Step two: the pending admin accepts and becomes the admin.
    pub fn accept_admin(env: Env) {
        let pending: Address = env
            .storage()
            .instance()
            .get(&DataKey::PendingAdmin)
            .unwrap_or_else(|| panic!("no pending admin"));
        pending.require_auth();
        extend_instance_ttl(&env);
        let old_admin: Address = env.storage().instance().get(&DataKey::Admin).unwrap();
        env.storage().instance().set(&DataKey::Admin, &pending);
        env.storage().instance().remove(&DataKey::PendingAdmin);
        AdminAccepted {
            old_admin,
            new_admin: pending,
        }
        .publish(&env);
    }

    /// The current admin withdraws a pending proposal.
    pub fn cancel_admin_proposal(env: Env) {
        let admin: Address = env.storage().instance().get(&DataKey::Admin).unwrap();
        admin.require_auth();
        extend_instance_ttl(&env);
        let pending: Address = env
            .storage()
            .instance()
            .get(&DataKey::PendingAdmin)
            .unwrap_or_else(|| panic!("no pending admin"));
        env.storage().instance().remove(&DataKey::PendingAdmin);
        AdminProposalCancelled { admin, pending }.publish(&env);
    }

    /// Return the amount of tokens vested so far according to the schedule.
    pub fn get_vested_amount(env: Env) -> i128 {
        let now = env.ledger().timestamp();
        let cliff: u64 = env.storage().instance().get(&DataKey::Cliff).unwrap();
        let end: u64 = env.storage().instance().get(&DataKey::End).unwrap();
        let total_amount: i128 = env.storage().instance().get(&DataKey::TotalAmount).unwrap();

        if now < cliff {
            return 0;
        }
        if now >= end {
            return total_amount;
        }

        // Linear interpolation: total * (now - cliff) / (end - cliff), computed
        // without multiplying the (up to i128) total_amount by elapsed directly,
        // since that product can exceed u128::MAX for large grants over long
        // durations. Split into a whole-unit term and a remainder term, where
        // the remainder term only multiplies two u64-derived values together.
        let elapsed = now - cliff;
        let duration = end - cliff;
        let total_u128 = total_amount as u128;
        let whole = total_u128 / duration as u128;
        let remainder = total_u128 % duration as u128;
        let vested = whole
            .checked_mul(elapsed as u128)
            .and_then(|v| remainder.checked_mul(elapsed as u128).map(|r| (v, r)))
            .and_then(|(v, r)| v.checked_add(r / duration as u128))
            .unwrap_or_else(|| panic!("vested amount calculation overflowed"));
        vested as i128
    }

    /// Return the amount that the beneficiary can currently claim
    /// (vested minus already claimed).
    pub fn get_claimable_amount(env: Env) -> i128 {
        let vested = Self::get_vested_amount(env.clone());
        let claimed: i128 = env.storage().instance().get(&DataKey::Claimed).unwrap();
        vested - claimed
    }

    /// Claim all currently vested tokens for the beneficiary.
    ///
    /// Transfers the newly vested amount (since the last claim) to the
    /// beneficiary. Can be called multiple times.
    pub fn claim(env: Env) -> i128 {
        let beneficiary: Address =
            env.storage().instance().get(&DataKey::Beneficiary).unwrap();
        beneficiary.require_auth();
        extend_instance_ttl(&env);

        let claimable = Self::get_claimable_amount(env.clone());
        if claimable <= 0 {
            panic_with_error!(&env, Error::NothingToClaim);
        }

        let claimed: i128 = env.storage().instance().get(&DataKey::Claimed).unwrap();
        env.storage()
            .instance()
            .set(&DataKey::Claimed, &(claimed + claimable));

        let token: Address = env.storage().instance().get(&DataKey::Token).unwrap();
        let client = token::Client::new(&env, &token);
        client.transfer(
            &env.current_contract_address(),
            &beneficiary,
            &claimable,
        );

        env.events()
            .publish((symbol_short!("claim"), beneficiary), claimable);

        claimable
    }
}

